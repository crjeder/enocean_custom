def _crc8(data: list[int]) -> int:
    csum = 0
    for b in data:
        csum = _CRC_TABLE[csum ^ (b & 0xFF)]
    return csum


def _esp3_frame(data: list[int], optional: list[int], packet_type: int) -> bytes:
    """Wrap data + optional into an ESP3 frame with correct CRCs."""
    data_len = len(data)
    opt_len = len(optional)
    header = [data_len >> 8, data_len & 0xFF, opt_len, packet_type]
    crc_h = _crc8(header)
    payload = data + optional
    crc_d = _crc8(payload)
    return bytes([0x55] + header + [crc_h] + payload + [crc_d])


# ── Packet builders ──────────────────────────────────────────────────────────

def rps_packet(sender_id: list[int], data_byte: int, status: int = 0x30) -> bytes:
    """RPS (F6) radio packet — e.g. wall switch press.

    sender_id: 4-byte list, e.g. [0xDE, 0xAD, 0xBE, 0x01]
    data_byte: e.g. 0x70 (button A1 pressed)
    """
    data = [0xF6, data_byte] + sender_id + [status]
    optional = [0x01, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00]
    return _esp3_frame(data, optional, packet_type=0x01)


def bs1_packet(sender_id: list[int], contact_open: bool = True) -> bytes:
    """1BS (D5) contact sensor packet — D5-00-01.

    contact_open=True  → data bit 0 = 0 (open)
    contact_open=False → data bit 0 = 1 (closed / magnet present)
    """
    contact_bit = 0x00 if contact_open else 0x01
    # D5 telegram: RORG(D5) + data + sender_id(4) + status
    data_byte = 0x08 | contact_bit  # LRN bit = 1 (data telegram, not teach-in)
    data = [0xD5, data_byte] + sender_id + [0x00]
    optional = [0x01, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00]
    return _esp3_frame(data, optional, packet_type=0x01)


def bs4_d2_05_00_packet(
    sender_id: list[int],
    position: int,
    command: int = 0x02,
) -> bytes:
    """VLD (D2) D2-05-00 roller shutter position/status report.

    position: 0–100 (percent open, 0=closed, 100=fully open)
    command:  0x02 = Position and Angle Report
    """
    # D2-05-00 CMD 0x02: byte0 = RORG(D2), byte1 = (cmd<<4)|channel,
    # byte2 = position (0-100), byte3-6 = sender_id, byte7 = status
    db0 = (command & 0x0F) << 4  # command in upper nibble, channel 0
    data = [0xD2, db0, position & 0xFF] + sender_id + [0x00]
    optional = [0x01, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00]
    return _esp3_frame(data, optional, packet_type=0x01)


def ute_teach_in_packet(sender_id: list[int], manufacturer_id: int = 0x07FF) -> bytes:
    """UTE teach-in request packet (RORG D4).

    Simulates a device initiating a bidirectional teach-in.
    """
    # UTE data: 12 bytes of EEP/manufacturer info + sender_id(4) + status
    m_lsb = manufacturer_id & 0xFF
    m_msb = (manufacturer_id >> 8) & 0x07
    # Byte 0: 0x91 = query teach-in, channel count=1, no EEP type specified
    ute_data = [
        0x91, 0x00, 0x00, 0x00,  # bytes 0-3: teach-in request header
        0x00, 0x00,              # bytes 4-5: EEP func/type
        m_lsb, m_msb,           # bytes 6-7: manufacturer ID
        0x00, 0x00, 0x00, 0x00, # bytes 8-11: reserved
    ]
    data = [0xD4] + ute_data + sender_id + [0x00]
    optional = [0x01, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00]
    return _esp3_frame(data, optional, packet_type=0x01)
